function getShellsForAtomicNumber(n: number): number[] {
  if (n === 1) return [1];
  if (n === 2) return [2];
  if (n <= 10) return [2, n - 2];
  if (n <= 18) return [2, 8, n - 10];
  if (n <= 36) return [2, 8, Math.min(18, Math.max(0, n - 10)), Math.max(0, n - 28)].filter(Boolean);
  return [2, 8, 18, Math.min(32, Math.max(0, n - 28)), Math.max(0, n - 60)].filter(Boolean);
}

